from __future__ import annotations

from collections.abc import Iterable, Sequence
from uuid import uuid4

from cloud_dast.contracts.plan import VerificationPlan
from cloud_dast.couplings import (
    FieldCoupling,
    couplings_from_plan,
    normalise_action,
)
from cloud_dast.extensions import TestCaseGenerator
from cloud_dast.model import (
    Check,
    JsonValue,
    MethodSpec,
    Observation,
    ScenarioPosition,
)
from cloud_dast.ports import EventPublisher, Guardrail, Target
from cloud_dast.qdl.graph import (
    QdlGraph,
)
from cloud_dast.runtime.coupling.resolve import Binder, Context
from cloud_dast.runtime.differential.results import (
    ConcurrencyPartialResult,
    PairPartialResult,
    PartialExecutionError,
    ReadBackPartialResult,
)
from cloud_dast.runtime.execution.checks import run_check, run_probes
from cloud_dast.runtime.limits import (
    check_budget_exhausted,
    scenario_layer_matches,
)
from cloud_dast.verification.differential.contracts import (
    ConcurrencyResult,
    IsolatedStandPolicy,
    ReadBackResult,
)
from cloud_dast.verification.differential.modes import (
    CONCURRENCY_MAX_WORKERS,
)
from cloud_dast.verification.invariant_projection import InvariantProjection


class Checker:
    """Execute generated checks for one scenario with injected policies."""

    def __init__(
        self,
        target: Target,
        generator: TestCaseGenerator,
        guardrail: Guardrail,
        event_bus: EventPublisher | None = None,
        readback_stand_policy: IsolatedStandPolicy | None = None,
    ) -> None:
        self._target = target
        self._generator = generator
        self._guardrail = guardrail
        self._event_bus = event_bus
        self._readback_stand_policy = readback_stand_policy or IsolatedStandPolicy()
        self._checks: list[Check] = []
        self._outputs: dict[str, tuple[Check, Observation | None, bool]] = {}
        self._couplings: tuple[FieldCoupling, ...] = ()
        self._evidence_graph: QdlGraph | None = None
        self._methods: dict[str, MethodSpec] = {}
        self._scenarios: dict[tuple[str, str], ScenarioPosition] = {}
        self._coupling_resolver = Binder()

    @property
    def checks(self) -> tuple[Check, ...]:
        """Checks generated by the most recent execution."""

        return tuple(self._checks)

    def reset_checks(self) -> None:
        """Forget checks from the previous workflow run."""

        self._checks = []
        self.reset_outputs()

    def reset_outputs(self) -> None:
        """Forget observations and declarations from the previous path."""

        self._outputs.clear()
        self._couplings = ()
        self._evidence_graph = None
        self._methods.clear()
        self._scenarios.clear()

    def set_coupling_context(
        self,
        plans: Sequence[tuple[VerificationPlan, MethodSpec, ScenarioPosition]],
        *,
        evidence_graph: QdlGraph | None = None,
        reset: bool = True,
        observations: Sequence[tuple[Check, Observation]] = (),
    ) -> None:
        """Refresh path declarations and retain actual occurrences without replay."""

        if reset:
            self.reset_outputs()
        self._evidence_graph = evidence_graph
        self._methods = {
            normalise_action(method.method_id): method for _, method, _ in plans
        }
        self._scenarios = {
            (normalise_action(method.method_id), scenario.scenario_id): scenario
            for _, method, scenario in plans
        }
        self._couplings = tuple(
            dict.fromkeys(
                coupling
                for plan, _, _ in plans
                for coupling in couplings_from_plan(plan.couplings)
            )
        )
        for check, observation in observations:
            previous = self._outputs.get(check.check_id)
            if previous is None or not previous[2]:
                self._outputs[check.check_id] = (check, observation, False)

    def execute(
        self,
        methods: Iterable[MethodSpec],
        invariants: Iterable[InvariantProjection],
        scenario: ScenarioPosition,
        max_checks: int | None = None,
    ) -> tuple[Observation, ...]:
        self.reset_checks()
        bindings = (
            (
                VerificationPlan(
                    plan_id=f"plan:{invariant.invariant_id}:{method.method_id}",
                    invariant_id=invariant.invariant_id,
                    method_id=method.method_id,
                    scenario_id=scenario.scenario_id,
                ),
                method,
                scenario,
                invariant,
                None,
            )
            for method in methods
            for invariant in invariants
        )
        return self.execute_bindings(bindings, max_checks=max_checks, reset=False)

    def execute_bindings(
        self,
        bindings: Iterable[
            tuple[
                VerificationPlan,
                MethodSpec,
                ScenarioPosition,
                JsonValue,
                str | None,
            ]
        ],
        max_checks: int | None = None,
        *,
        reset: bool = True,
    ) -> tuple[Observation, ...]:
        """Execute bindings, optionally continuing a stateful campaign.

        ``reset=False`` continues the path context set by the caller, allowing
        declared couplings to bind earlier observations into next inputs.
        Callers starting an independent batch keep the default reset behavior.
        """
        if reset:
            self.reset_checks()
            bindings = tuple(bindings)
            self.set_coupling_context(
                tuple(
                    (plan, method, scenario) for plan, method, scenario, *_ in bindings
                )
            )
        observations: list[Observation] = []
        for plan, method, scenario, invariant, strategy in bindings:
            if check_budget_exhausted(len(observations), max_checks):
                break
            if not scenario_layer_matches(scenario, method):
                continue
            for check in self._binding_generator(strategy).generate(
                plan,
                method,
                invariant,
                scenario,
            ):
                if check_budget_exhausted(len(observations), max_checks):
                    break
                executed = self._execute_forwarded(check)
                if executed is None:
                    continue
                observations.append(executed[1])
        return tuple(observations)

    def execute_check(self, check: Check) -> Observation | None:
        """Execute one already generated check, continuing stateful output."""

        executed = self._execute_forwarded(check)
        return None if executed is None else executed[1]

    def generate_pair_checks(
        self,
        plan: VerificationPlan,
        method: MethodSpec,
        invariant: InvariantProjection,
        scenario: ScenarioPosition,
        *,
        strategy: str | None = None,
    ) -> tuple[Check, ...]:
        """Generate checks for one binding without executing them."""

        if not scenario_layer_matches(scenario, method):
            return ()
        return tuple(
            self._binding_generator(strategy).generate(
                plan,
                method,
                invariant,
                scenario,
            )
        )

    def execute_pair(
        self,
        control: Check,
        treatment: Check,
    ) -> tuple[
        tuple[Check, Observation] | None,
        tuple[Check, Observation] | None,
    ]:
        """Execute a control/treatment pair from one output snapshot.

        Stateful output forwarding must not leak between differential legs:
        each leg starts from the snapshot captured before the pair, and the
        snapshot is restored afterwards so the pair leaves the forwarding
        state of the surrounding campaign unchanged.  Each leg returns the
        executed check (forwarding may rewrite its request) together with its
        observation, or ``None`` when the guardrail blocked it.
        """

        snapshot = dict(self._outputs)
        calls_before = len(self._checks)
        first: tuple[Check, Observation] | None = None
        second: tuple[Check, Observation] | None = None
        try:
            try:
                first = self._execute_from_snapshot(control, snapshot)
                second = self._execute_from_snapshot(treatment, snapshot)
            except Exception as error:
                partial = self._pair_partial(calls_before, first, second)
                raise PartialExecutionError(
                    "differential pair failed after partial execution",
                    result=partial,
                ) from error
        finally:
            self._restore_outputs(snapshot)
        return first, second

    def execute_readback(
        self,
        write_check: Check,
        read_check: Check,
        *,
        resource_binding: str,
    ) -> ReadBackResult:
        """Execute read-before → write → read-after from one snapshot.

        The three legs share one output-forwarding snapshot (restored
        afterwards), so no leg receives another's response fields.  The
        read-after request is re-bound to the resource id resolved from
        the write response; when the write echoes no id, the binding falls
        back to the id the read-before leg actually sent.  Raises
        ``ValueError`` when a leg is guardrail-blocked or the resource id
        cannot be resolved.
        """

        self._readback_stand_policy.validate_write_check(write_check)
        snapshot = dict(self._outputs)
        calls_before = len(self._checks)
        before: tuple[Check, Observation] | None = None
        write: tuple[Check, Observation] | None = None
        after: tuple[Check, Observation] | None = None
        try:
            try:
                before = self._execute_from_snapshot(read_check, snapshot)
                write = self._execute_from_snapshot(write_check, snapshot)
                if before is None or write is None:
                    raise PartialExecutionError(
                        "read-back requires all legs to pass the guardrail",
                        result=self._readback_partial(
                            calls_before,
                            before,
                            write,
                            after,
                        ),
                    )
                before_check, before_observation = before
                write_executed, write_observation = write
                resource_id = _resolve_resource_id(
                    write_observation,
                    before_check,
                    resource_binding,
                )
                after_check = _bind_resource(
                    read_check,
                    resource_binding,
                    resource_id,
                )
                after = self._execute_from_snapshot(after_check, snapshot)
                if after is None:
                    raise PartialExecutionError(
                        "read-back requires all legs to pass the guardrail",
                        result=self._readback_partial(
                            calls_before,
                            before,
                            write,
                            after,
                        ),
                    )
                after_executed, after_observation = after
            except PartialExecutionError:
                raise
            except Exception as error:
                raise PartialExecutionError(
                    "read-back failed after partial execution",
                    result=self._readback_partial(
                        calls_before,
                        before,
                        write,
                        after,
                    ),
                ) from error
        finally:
            self._restore_outputs(snapshot)
        return ReadBackResult(
            write_check=write_executed,
            read_before_check=before_check,
            read_after_check=after_executed,
            write=write_observation,
            read_before=before_observation,
            read_after=after_observation,
        )

    def execute_parallel_batch(
        self,
        probes: Sequence[Check],
        *,
        read_before: Check | None = None,
        read_after: Check | None = None,
        max_workers: int = CONCURRENCY_MAX_WORKERS,
    ) -> ConcurrencyResult:
        """Execute read-before, parallel probes, and read-after in isolation.

        Every request is first forwarded from one output snapshot.  The probe
        batch then invokes the target concurrently; probe responses are not
        forwarded into one another or into the read-after request.  The
        snapshot is restored after the batch, just as for pair and read-back
        execution.
        """

        if max_workers < 1:
            raise ValueError("max_workers must be positive")
        snapshot = dict(self._outputs)
        before_prepared = self._prepare_from_snapshot(read_before, snapshot)
        probe_checks = tuple(
            self._prepare_from_snapshot(probe, snapshot) for probe in probes
        )
        after_prepared = self._prepare_from_snapshot(read_after, snapshot)
        if (
            (read_before is not None and before_prepared is None)
            or (read_after is not None and after_prepared is None)
            or any(probe is None for probe in probe_checks)
        ):
            self._restore_outputs(snapshot)
            raise PartialExecutionError(
                "concurrency batch requires all legs to pass the guardrail",
                result=ConcurrencyPartialResult((), ()),
            )

        before_result = None
        after_result = None
        probe_results: list[tuple[Check, Observation | None]] = []
        calls_before = len(self._checks)
        execution_error: Exception | None = None
        try:
            if read_before is not None:
                self._outputs = dict(snapshot)
                before_result = self._execute_forwarded(before_prepared)
            if probe_checks:
                self._outputs = dict(snapshot)
                self._checks.extend(probe_checks)
                execution_error = run_probes(
                    probe_checks,
                    self._target,
                    self._event_bus,
                    probe_results,
                    max_workers=max_workers,
                )
            if execution_error is None and read_after is not None:
                self._outputs = dict(snapshot)
                after_result = self._execute_forwarded(after_prepared)
        except Exception as error:
            if execution_error is None:
                execution_error = error
        finally:
            self._restore_outputs(snapshot)

        if execution_error is not None:
            partial = self._concurrency_partial(
                calls_before,
                before_result,
                after_result,
                tuple(probe_results),
            )
            raise PartialExecutionError(
                "concurrency batch failed after partial execution",
                result=partial,
            ) from execution_error
        if any(
            result is None
            for requested, result in (
                (read_before, before_result),
                (read_after, after_result),
            )
            if requested is not None
        ):
            raise PartialExecutionError(
                "concurrency batch requires all legs to pass the guardrail",
                result=self._concurrency_partial(
                    calls_before,
                    before_result,
                    after_result,
                    tuple(probe_results),
                ),
            )
        return ConcurrencyResult(
            read_before=before_result,
            read_after=after_result,
            probes=tuple(probe_results),
        )

    def _pair_partial(
        self,
        calls_before: int,
        control: tuple[Check, Observation] | None,
        treatment: tuple[Check, Observation] | None,
    ) -> PairPartialResult:
        observations = self._partial_observations((control, treatment))
        return PairPartialResult(
            checks=tuple(self._checks[calls_before:]),
            observations=observations,
            failed_checks=self._failed_checks(calls_before, observations),
            control=control,
            treatment=treatment,
        )

    def _readback_partial(
        self,
        calls_before: int,
        read_before: tuple[Check, Observation] | None,
        write: tuple[Check, Observation] | None,
        read_after: tuple[Check, Observation] | None,
    ) -> ReadBackPartialResult:
        observations = self._partial_observations((read_before, write, read_after))
        return ReadBackPartialResult(
            checks=tuple(self._checks[calls_before:]),
            observations=observations,
            failed_checks=self._failed_checks(calls_before, observations),
            read_before=read_before,
            write=write,
            read_after=read_after,
        )

    def _concurrency_partial(
        self,
        calls_before: int,
        read_before: tuple[Check, Observation] | None,
        read_after: tuple[Check, Observation] | None,
        probes: tuple[tuple[Check, Observation], ...],
    ) -> ConcurrencyPartialResult:
        observations = self._partial_observations((read_before, read_after, *probes))
        return ConcurrencyPartialResult(
            checks=tuple(self._checks[calls_before:]),
            observations=observations,
            failed_checks=self._failed_checks(calls_before, observations),
            read_before=read_before,
            read_after=read_after,
            probes=probes,
        )

    @staticmethod
    def _partial_observations(
        results: Iterable[tuple[Check, Observation] | None],
    ) -> tuple[Observation, ...]:
        return tuple(
            observation
            for result in results
            if result is not None
            for observation in (result[1],)
        )

    def _failed_checks(
        self,
        calls_before: int,
        observations: tuple[Observation, ...],
    ) -> tuple[Check, ...]:
        completed = {observation.check_id for observation in observations}
        return tuple(
            check
            for check in self._checks[calls_before:]
            if check.check_id not in completed
        )

    def _binding_generator(self, strategy: str | None) -> TestCaseGenerator:
        return (
            self._generator.select(strategy)
            if strategy is not None and hasattr(self._generator, "select")
            else self._generator
        )

    def _execute_forwarded(
        self,
        check: Check,
    ) -> tuple[Check, Observation] | None:
        """Execute one check with the current output-forwarding state."""

        check = self.resolve_check(check)
        if check is None or not self._guardrail.allows(check):
            return None
        self._checks.append(check)
        declared = (
            normalise_action(check.method_id),
            check.scenario_id,
        ) in self._scenarios
        if declared:
            self._outputs[check.check_id] = (check, None, True)
        observation = run_check(check, self._target, self._event_bus)
        if declared:
            self._outputs[check.check_id] = (check, observation, True)
        return check, observation

    def _execute_from_snapshot(
        self,
        check: Check,
        snapshot: dict[str, tuple[Check, Observation | None, bool]],
    ) -> tuple[Check, Observation] | None:
        """Execute one leg of a pair starting from a shared snapshot."""

        self._outputs = dict(snapshot)
        return self._execute_forwarded(check)

    def _restore_outputs(
        self, snapshot: dict[str, tuple[Check, Observation | None, bool]]
    ) -> None:
        """Restore the active path's forwarding state after isolated legs."""

        self._outputs = dict(snapshot)

    def _prepare_from_snapshot(
        self,
        check: Check | None,
        snapshot: dict[str, tuple[Check, Observation | None, bool]],
    ) -> Check | None:
        """Forward one leg from a snapshot without executing it."""

        if check is None:
            return None
        self._outputs = dict(snapshot)
        forwarded = self.resolve_check(check)
        return (
            forwarded
            if forwarded is not None and self._guardrail.allows(forwarded)
            else None
        )

    def resolve_check(self, check: Check) -> Check | None:
        """Resolve a joint value witness, then check this call's causal requires."""

        return self._coupling_resolver.resolve_check(
            check,
            Context(
                couplings=self._couplings,
                evidence_graph=self._evidence_graph,
                methods=self._methods,
                scenarios=self._scenarios,
                outputs=self._outputs,
            ),
        )


def _resolve_resource_id(
    write: Observation,
    before_check: Check,
    binding: str,
) -> object:
    """Resolve the written resource id from the write response.

    The write response is authoritative when it echoes the id; otherwise
    the id the read-before leg actually sent is the best measured binding.
    """

    if write.output is not None:
        resolved = dict(write.output.fields).get(binding)
        if resolved is not None:
            return resolved
    resolved = dict(before_check.request).get(binding)
    if resolved is None:
        raise ValueError(
            f"read-back could not resolve resource id from field {binding!r}"
        )
    return resolved


def _bind_resource(
    check: Check,
    binding: str,
    resource_id: object,
) -> Check:
    """Re-bind one request field of the read check to the written id."""

    request = dict(check.request)
    request[binding] = resource_id
    return check.model_copy(
        update={"check_id": uuid4().hex, "request": tuple(request.items())}
    )
