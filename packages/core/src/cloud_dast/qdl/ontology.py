"""QDL ontology: term-shape and predicate schemas."""

from __future__ import annotations

from enum import StrEnum
from typing import Literal, Self

from pydantic import BaseModel, ConfigDict, Field, model_validator

type AtomType = Literal["string", "integer", "float", "boolean"]
type PredicateVerificationClass = Literal[
    "runtime_falsifiable",
    "evidence_gated",
    "structural",
]


class TermKind(StrEnum):
    """Ground term kinds accepted by predicate and constructor schemas."""

    ATOM = "atom"
    STRUCT = "struct"


class ArgumentSchema(BaseModel):
    """Term-shape constraints for one predicate or constructor argument."""

    model_config = ConfigDict(frozen=True, validate_assignment=True)

    name: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    ground_types: tuple[TermKind, ...] = (TermKind.ATOM, TermKind.STRUCT)
    atom_types: tuple[AtomType, ...] | None = None
    struct_names: tuple[str, ...] | None = None
    reference: bool = False
    declaration: bool = False


class StructSchema(BaseModel):
    """Declarative schema for a structural term constructor."""

    model_config = ConfigDict(frozen=True, validate_assignment=True)

    name: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    arguments: tuple[ArgumentSchema, ...]
    optional_arguments: tuple[ArgumentSchema, ...] = ()

    @property
    def arity(self) -> int:
        return len(self.arguments)

    @property
    def all_arguments(self) -> tuple[ArgumentSchema, ...]:
        return (*self.arguments, *self.optional_arguments)


def _identifier(name: str, reference: bool = False) -> ArgumentSchema:
    return ArgumentSchema(
        name=name,
        ground_types=(TermKind.ATOM,),
        atom_types=("string",),
        reference=reference,
    )


"""Constructors accepted by ``causes`` and ``prevents``.

A causal effect is a state of the world that an action can produce and that a
norm can forbid.  Runtime evidence such as a response status is deliberately
excluded: it is something we observe, not something a norm forbids.
"""

CAUSAL_EFFECT_CONSTRUCTORS: tuple[str, ...] = (
    "allowed",
    "changed",
    "completed",
    "create",
    "denied",
    "duration",
    "external_call",
    "has",
    "identity",
    "reached",
    "remove",
    "transition",
)

"""Constructors accepted by ``evidence``.

In addition to causal effects, observations can carry witness-channel evidence
(``field``/``error``/``marker``), runtime evidence
(``response_status``/``outcome``), and adapter triage evidence
(``source``/``unmapped``/``ambiguous``).  None of these evidence-only
constructors may be used as a ``prevents`` violation effect.
"""

EVIDENCE_EFFECT_CONSTRUCTORS: tuple[str, ...] = (
    *CAUSAL_EFFECT_CONSTRUCTORS,
    "field",
    "error",
    "marker",
    "response_status",
    "outcome",
    "source",
    "unmapped",
    "ambiguous",
    "differs",
)

"""Witness constructors — the closed channel alphabet of the security algebra.

Every attacker-measurable quantity of an API interaction is generated by
these six constructors (see docs/qdl-algebra.md, channel lemma).  They are
channels, not values: ``status(a)`` is the status *channel* of an action,
while ``response_status(a, code)`` is a recorded evidence *value*.
"""

WITNESS_CONSTRUCTORS: tuple[str, ...] = (
    "field",
    "output_field",
    "output_header",
    "status",
    "error",
    "latency",
    "callback",
    "trace",
)


def _causal_effect(name: str) -> ArgumentSchema:
    return ArgumentSchema(
        name=name,
        ground_types=(TermKind.STRUCT,),
        struct_names=CAUSAL_EFFECT_CONSTRUCTORS,
    )


def _evidence_effect(name: str) -> ArgumentSchema:
    return ArgumentSchema(
        name=name,
        ground_types=(TermKind.STRUCT,),
        struct_names=EVIDENCE_EFFECT_CONSTRUCTORS,
    )


def _witness(name: str) -> ArgumentSchema:
    return ArgumentSchema(
        name=name,
        ground_types=(TermKind.ATOM, TermKind.STRUCT),
        struct_names=WITNESS_CONSTRUCTORS,
        reference=True,
    )


def _node(name: str) -> ArgumentSchema:
    """Polymorphic graph node: an atom or any structural term."""

    return ArgumentSchema(
        name=name,
        ground_types=(TermKind.ATOM, TermKind.STRUCT),
        reference=True,
    )


