class Predicate(BaseModel):
    """A predicate symbol carrying the schema used to validate its facts."""

    model_config = ConfigDict(frozen=True, validate_assignment=True)

    name: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    definition: PredicateSchema

    @model_validator(mode="before")
    @classmethod
    def prefer_builtin_definition(cls, data: object) -> object:
        """Coerce stored definitions to the current basis.

        Persisted projections may embed historical extension schemas for
        predicates that were later promoted to built-ins (e.g. ``targets``).
        The current basis is the source of truth: on deserialization the
        built-in definition always wins, so old graphs load without a
        spurious "redefinition" failure.
        """

        if isinstance(data, dict):
            builtin = _PREDICATE_SCHEMA_BY_NAME.get(data.get("name"))
            if builtin is not None:
                data = {**data, "definition": builtin.model_dump()}
        return data

    @model_validator(mode="after")
    def validate_predicate(self) -> Self:
        if self.definition.name != self.name:
            raise ValueError(
                f"predicate name {self.name} does not match schema "
                f"{self.definition.name}"
            )
        builtin = _PREDICATE_SCHEMA_BY_NAME.get(self.name)
        if builtin is not None and builtin != self.definition:
            raise ValueError(f"built-in predicate cannot be redefined: {self.name}")
        return self

    @classmethod
    def from_name(cls, name: str) -> Self:
        schema = _PREDICATE_SCHEMA_BY_NAME.get(name)
        if schema is None:
            raise ValueError(f"unknown predicate: {name}")
        return cls(name=name, definition=schema)

    @classmethod
    def from_schema(cls, schema: PredicateSchema) -> Self:
        builtin = _PREDICATE_SCHEMA_BY_NAME.get(schema.name)
        if builtin is not None:
            raise ValueError(f"built-in predicate cannot be redefined: {schema.name}")
        return cls(name=schema.name, definition=schema)

    @property
    def arity(self) -> int:
        return self.definition.arity


