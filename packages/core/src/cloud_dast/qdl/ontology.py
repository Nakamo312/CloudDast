"""Verification classes for predicates that exist in both the core and
extension registries.

The mapping is an ontology default, not a second predicate registry: schemas
may explicitly override ``verification_class``, while legacy constructors omit
the field and inherit the class for their predicate name.  Contract
declarations remain structural; sink-type values carried by ``is`` remain a
promotion-policy exception because their proof is evidence-gated.
"""

_RUNTIME_FALSIFIABLE_PREDICATES = frozenset(
    {"causes", "exposes", "requires", "targets", "refers_to"}
)
_EVIDENCE_GATED_PREDICATES = frozenset({"has", "sink_interprets"})
_PREDICATE_VERIFICATION_CLASSES: dict[str, PredicateVerificationClass] = {
    **dict.fromkeys(_RUNTIME_FALSIFIABLE_PREDICATES, "runtime_falsifiable"),
    **dict.fromkeys(_EVIDENCE_GATED_PREDICATES, "evidence_gated"),
}


class PredicateSchema(BaseModel):
    """Declarative, extensible schema for a predicate."""

    model_config = ConfigDict(frozen=True, validate_assignment=True)

    name: str = Field(pattern=r"^[a-z][a-z0-9_]*$")
    arguments: tuple[ArgumentSchema, ...]
    verification_class: PredicateVerificationClass = "structural"

    @model_validator(mode="before")
    @classmethod
    def infer_verification_class(cls, data: object) -> object:
        """Inherit the ontology class when a legacy schema omits it."""

        if not isinstance(data, dict) or "verification_class" in data:
            return data
        name = data.get("name")
        if not isinstance(name, str):
            return data
        return {
            **data,
            "verification_class": _PREDICATE_VERIFICATION_CLASSES.get(
                name, "structural"
            ),
        }

    @property
    def arity(self) -> int:
        return len(self.arguments)


